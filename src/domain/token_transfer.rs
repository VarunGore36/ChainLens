#[cfg(test)]
mod tests {
    use super::*;
    use alloy_primitives::keccak256;

    #[test]
    fn transfer_topic_matches_keccak() {
        let expected = keccak256("Transfer(address,address,uint256)");
        assert_eq!(TRANSFER_TOPIC, expected);
    }

    #[test]
    fn approval_topic_matches_keccak() {
        let expected = keccak256("Approval(address,address,uint256)");
        assert_eq!(APPROVAL_TOPIC, expected);
    }

    #[test]
    fn erc1155_single_topic_matches_keccak() {
        let expected = keccak256("TransferSingle(address,address,address,uint256,uint256)");
        assert_eq!(ERC1155_TRANSFER_SINGLE_TOPIC, expected);
    }

    #[test]
    fn erc1155_batch_topic_matches_keccak() {
        let expected = keccak256("TransferBatch(address,address,address,uint256[],uint256[])");
        assert_eq!(ERC1155_TRANSFER_BATCH_TOPIC, expected);
    }
}
