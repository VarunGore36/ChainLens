use alloy_primitives::{Address, B256, U256};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum TokenStandard {
    Erc20,
    Erc721,
    Erc1155,
}

#[derive(Debug, Clone)]
pub struct TokenTransfer {
    pub block_number: u64,
    pub log_index: u32,
    pub token_address: Address,
    pub from: Address,
    pub to: Address,
    pub value: U256,
    pub token_id: U256,
    pub standard: TokenStandard,
}

